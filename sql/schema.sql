CREATE TABLE IF NOT EXISTS rfq_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(300) NOT NULL,
  company VARCHAR(300) NOT NULL,
  email VARCHAR(300) NOT NULL,
  phone VARCHAR(80) NOT NULL,
  product VARCHAR(80) NOT NULL DEFAULT '',
  quote_items TEXT NULL,
  message TEXT NOT NULL,
  attachment_path VARCHAR(255) NULL,
  attachment_type TEXT NULL,
  attachment_data BYTEA NULL,
  mail_sent BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS catalog_categories (
  slug VARCHAR(80) PRIMARY KEY,
  title VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS catalog_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_slug VARCHAR(80) NOT NULL,
  item_id VARCHAR(80) NOT NULL,
  name VARCHAR(200) NOT NULL,
  image TEXT NOT NULL DEFAULT '',
  packs JSONB NOT NULL,
  description TEXT NOT NULL,
  applications TEXT NOT NULL,
  specifications JSONB NOT NULL,
  summary VARCHAR(400) NOT NULL DEFAULT '',
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (category_slug, item_id)
);

CREATE OR REPLACE FUNCTION aero_touch_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

ALTER TABLE rfq_submissions ADD COLUMN IF NOT EXISTS attachment_type TEXT;
ALTER TABLE rfq_submissions ADD COLUMN IF NOT EXISTS attachment_data BYTEA;

DROP TRIGGER IF EXISTS catalog_items_updated_at ON catalog_items;
CREATE TRIGGER catalog_items_updated_at
  BEFORE UPDATE ON catalog_items
  FOR EACH ROW EXECUTE FUNCTION aero_touch_updated_at();
